const mongoose = require('mongoose');

const universitySchema = new mongoose.Schema({
  name: { type: String, required: true, trim: true },
  shortName: String,
  campus: String,
  city: { type: String, required: true },
  province: String,
  sector: { type: String, enum: ['Public', 'Private', 'Semi-Government'], default: 'Public' },
  type: { type: String, enum: ['General', 'Engineering', 'Medical', 'Business', 'Arts'], default: 'General' },
  category: String,
  ranking: Number,
  HECNationalUniversityRanking: Number,
  qsRanking: Number,
  established: Number,
  website: String,
  logo: String,
  image: String,
  campusImage: String,
  description: String,
  programs: [{
    name: String,
    department: String,
    faculty: String,
    degreeLevel: { type: String, enum: ['Bachelors', 'Masters', 'PhD', 'Diploma'] },
    duration: String,
    creditHours: Number,
    feePerSemester: Number,
    annualFee: Number,
    admissionFee: Number,
    registrationFee: Number,
    hostelFee: Number,
    transportFee: Number,
    securityDeposit: Number,
    otherCharges: Number,
    seats: Number,
    reservedSeats: Number,
    meritFormula: String,
    lastYearMerit: Number,
  }],
  facilities: {
    library: Boolean,
    transport: Boolean,
    hostels: Boolean,
    sports: Boolean,
    medical: Boolean,
    mosque: Boolean,
    cafeteria: Boolean,
    wifi: Boolean,
    computerLabs: Boolean,
    researchLabs: Boolean,
  },
  admissionStatus: {
    isOpen: { type: Boolean, default: false },
    openDate: String,
    closeDate: String,
    lastDate: String,
    applicationDeadline: String,
    schedule: String,
    applyOnlineLink: String,
    prospectusLink: String,
    advertisementPdf: String,
    meritLists: [String],
    meritListDates: [String],
    entryTestRequired: Boolean,
    entryTestDate: String,
    interviewDate: String,
    resultDate: String,
  },
  admissionCriteria: {
    minPercentage: Number,
    minCGPA: Number,
    matricPercentage: Number,
    fscPercentage: Number,
    requiredSubjects: [String],
    requiredDocuments: [String],
    entryTestPercentage: Number,
    entryTest: String,
    lastMerit: Number,
    meritFormula: String,
  },
  scholarships: [{
    name: String,
    type: String,
    amount: String,
    eligibility: String,
    description: String,
  }],
  financialAid: [String],
  contact: {
    phone: String,
    email: String,
    admissionOffice: String,
    address: String,
    googleMapsLocation: String,
    facebook: String,
    instagram: String,
    linkedin: String,
    twitter: String,
    youtube: String,
  },
  latestNews: [String],
  admissionNotices: [String],
  announcements: [String],
  upcomingEvents: [String],
  academicCalendar: String,
  pdfDocuments: [{
    url: String,
    text: String,
    extractedAt: Date,
  }],
  rating: { type: Number, default: 0, min: 0, max: 5 },
}, { timestamps: true });

universitySchema.index({ name: 'text', city: 'text', description: 'text', website: 1 });

module.exports = mongoose.model('University', universitySchema);
